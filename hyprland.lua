-- Hyprland 0.57 Lua config — main entry.
-- Replaces the legacy hyprland.conf (which sourced hyprland/*.conf + custom/*.conf).
-- custom/ is a symlink to ~/dotfiles/hypr-custom; custom files are loaded after
-- framework files so their values win, matching the old `source=` order.

local QS_CONFIG = "ii"
_G.QS_CONFIG = QS_CONFIG -- shared with dofile()'d files
-- quickshell >=0.3.2 matches running instances by the RESOLVED config path, so
-- `qs -c ii` can't find the instance started through the ~/.config/quickshell
-- symlink. Always invoke with the real path:
_G.QS_PATH = "/home/dan/dotfiles/quickshell/" .. QS_CONFIG

-- Ensure binds are live even after a reload from a nested submap
-- (legacy: `exec = hyprctl dispatch submap global` + `submap = global`)
hl.on("hyprland.start", function() hl.dispatch(hl.dsp.submap("reset")) end)
hl.on("config.reloaded", function() hl.dispatch(hl.dsp.submap("reset")) end)

-- Defaults (framework, illogical-impulse)
dofile("/home/dan/.config/hypr/hyprland/env.lua")
local okx, errx = pcall(dofile, "/home/dan/.config/hypr/hyprland/execs.lua")
if not okx then print("execs.lua failed to load: " .. tostring(errx)) end
dofile("/home/dan/.config/hypr/hyprland/general.lua")
dofile("/home/dan/.config/hypr/hyprland/rules.lua")
dofile("/home/dan/.config/hypr/hyprland/colors.lua")
dofile("/home/dan/.config/hypr/hyprland/keybinds.lua")

-- Custom overrides (loaded later = higher precedence, like the old source order)
dofile("/home/dan/.config/hypr/custom/env.lua")
dofile("/home/dan/.config/hypr/custom/execs.lua")
dofile("/home/dan/.config/hypr/custom/general.lua")
dofile("/home/dan/.config/hypr/custom/rules.lua")
dofile("/home/dan/.config/hypr/custom/keybinds.lua")

-- nwg-displays (regenerated by nwg-displays; was `source=monitors.conf`)
dofile("/home/dan/.config/hypr/monitors.lua")

-- was: exec-once = dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP
hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
end)

